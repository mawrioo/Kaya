import { expect, test } from "./browser-fixtures"

test.beforeEach(async ({ request }) => {
  const reset = await request.post("http://127.0.0.1:4200/__test/reset", { headers: { authorization: process.env.KAYA_BROWSER_TOKEN! } })
  expect(reset.ok()).toBe(true)
})

for (const theme of ["light", "dark"] as const) {
  test(`selected Home design fits six wallets and preserves privacy (${theme})`, async ({ page, request }, info) => {
    for (const name of ["Mandiri", "Cash"]) expect((await request.post("/api/wallets", { data: { name, kind: "bank", startingBalance: 25000000 } })).ok()).toBe(true)
    await page.addInitScript(value => localStorage.setItem("theme", value), theme)
    await page.setViewportSize({ width: 390, height: 844 })
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    await page.goto("/")
    const nav = page.getByRole("navigation", { name: "Phone navigation" })
    const plus = nav.getByRole("button", { name: "Quick add", exact: true })
    await expect(plus).toBeEnabled()
    await page.evaluate(() => document.fonts.ready)
    const pattern = page.locator(".phone-balance-pattern")
    await expect(pattern).toBeVisible()
    expect(await pattern.evaluate(node => getComputedStyle(node).backgroundImage)).toContain("/patterns/kawung-phone.svg")
    await expect(pattern).toHaveCSS("mask-image", "none")
    await expect(pattern).toHaveCSS("filter", "none")
    const tile = await request.get("/patterns/kawung-phone.svg")
    expect(tile.ok()).toBe(true)
    expect(tile.headers()["content-type"]).toContain("image/svg+xml")
    expect((await nav.boundingBox())!.height).toBe(52)
    expect(await nav.locator("a,button").evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height).every(height => height >= 44))).toBe(true)
    const box = (await plus.boundingBox())!
    expect(box.x + box.width / 2).toBeCloseTo(195, 0)
    expect((await plus.innerText()).trim()).toBe("")
    expect((await plus.locator("span").boundingBox())!.width).toBe(40)
    await expect(page.getByRole("button", { name: "Balance breakdown", exact: true })).toHaveCount(0)
    const wallets = page.getByRole("region", { name: "Wallets", exact: true })
    await expect(wallets.getByRole("listitem")).toHaveCount(6)
    const last = (await wallets.getByRole("listitem").last().boundingBox())!
    expect(last.y + last.height).toBeLessThan((await nav.boundingBox())!.y)
    const amount = page.locator(".phone-total-money")
    const numeric = await amount.evaluate(node => ({ font: getComputedStyle(node).fontFamily, variant: getComputedStyle(node).fontVariantNumeric, style: getComputedStyle(node).fontStyle }))
    expect(numeric.variant).toContain("lining-nums")
    expect(numeric.variant).toContain("tabular-nums")
    expect(numeric.style).toBe("normal")
    expect(await nav.locator('[aria-current="page"]').evaluate(node => getComputedStyle(node).backgroundColor)).toBe("rgba(0, 0, 0, 0)")
    await page.screenshot({ path: info.outputPath(`${theme}-home.png`), animations: "disabled" })
    await page.getByRole("button", { name: "Hide BCA balance", exact: true }).click()
    await page.getByRole("button", { name: "Hide total balance", exact: true }).click()
    await page.reload()
    await expect(page.getByRole("button", { name: "Show BCA balance", exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "Show total balance", exact: true })).toBeVisible()
    await expect(amount).toContainText("Amount hidden")
    expect(errors).toEqual([])
    await page.setViewportSize({ width: 1440, height: 1000 })
    await expect(pattern).toBeHidden()
    await page.screenshot({ path: info.outputPath(`${theme}-desktop.png`), animations: "disabled" })
  })
}

test("one Quick add draft survives viewport changes and returns to a visible trigger", async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/transactions")
  const count = ((await (await request.get("/api/data")).json()).transactions as unknown[]).length
  const nav = page.getByRole("navigation", { name: "Phone navigation" })
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.getByLabel("What happened?", { exact: true }).fill("paid 35rb Food BCA today")
  await expect(page.getByRole("dialog")).toHaveCount(1)
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(page.getByLabel("What happened?", { exact: true })).toHaveValue("paid 35rb Food BCA today")
  await page.keyboard.press("Escape")
  await expect(page.getByRole("button", { name: "Quick add", exact: true })).toBeFocused()
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(nav).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(nav.getByRole("button", { name: "Quick add", exact: true })).toBeFocused()
  await expect(nav.getByRole("link", { name: "Transactions", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(nav.getByRole("button", { name: "Quick add", exact: true })).not.toHaveAttribute("aria-current")
  await nav.getByRole("button", { name: "More pages", exact: true }).click()
  await page.keyboard.press("Control+k")
  await expect(page.getByRole("dialog")).toHaveCount(1)
  await expect(page.getByRole("dialog", { name: "More", exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.locator('[role="dialog"]')).toHaveCount(0)
  await page.keyboard.press("Control+k")
  await expect(page.getByRole("dialog", { name: "Quick add", exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  expect(((await (await request.get("/api/data")).json()).transactions as unknown[]).length).toBe(count)
})

test("large figures, long names and below-zero privacy remain readable", async ({ page, request }) => {
  const negative = await request.post("/api/wallets", { data: { name: "Below zero", kind: "bank", startingBalance: 0 } })
  expect(negative.ok()).toBe(true)
  const negativeWallet = await negative.json()
  const data = await (await request.get("/api/data")).json()
  const category = data.categories.find((item: { type: string }) => item.type === "expense")
  const debit = await request.post("/api/transactions", { data: { type: "expense", amount: 5000, walletId: negativeWallet.wallet.id, categoryId: category.id, date: "2026-10-29T12:00:00+07:00", description: "Below-zero fixture" } })
  expect(debit.ok(), await debit.text()).toBe(true)
  const large = await request.post("/api/wallets", { data: { name: "Family savings with a longer wallet name", kind: "bank", startingBalance: 987654321000 } })
  expect(large.ok()).toBe(true)
  for (const width of [320, 360, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto("/")
    await expect(page.locator('[data-slot="overdrawn-list"]')).toContainText("5.000")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const row = page.getByRole("region", { name: "Wallets", exact: true }).getByRole("listitem").filter({ hasText: "Family savings" })
    await expect(row).toContainText("987.654.321.000")
    expect(await row.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  }
  await page.getByRole("button", { name: "Hide Below zero balance", exact: true }).click()
  await expect(page.locator('[data-slot="overdrawn-list"]')).not.toContainText("5.000")
  await page.getByRole("button", { name: "Hide total balance", exact: true }).click()
  await expect(page.locator(".phone-total-money")).toHaveCSS("font-size", "34px")
})
