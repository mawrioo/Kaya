import { expect, test } from "./browser-fixtures"

const today = new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Jakarta" }).format(new Date())

test.describe.configure({ mode: "serial" })
const read = async (request: import("@playwright/test").APIRequestContext) => (await request.get("/api/data")).json()

test("sample data is isolated", async ({ page, request }) => {
  const data = await read(request)
  expect(data.transactions).toHaveLength(41)
  expect(data.wallets.find((w: { id: string }) => w.id === "wallet-bca").balance).toBe(8_742_300)
  await page.goto("/wallets")
  await expect(page.getByRole("main")).toContainText("8.742.300")
})

test("principal corrections and settlement Undo update both wallets immediately and survive reload", async ({ page, request }, info) => {
  const response = await request.post("/api/wallets", { data: {
    name: "Review deposito", kind: "deposito", startingBalance: 1_000_000,
    deposito: { ratePercent: 5, startDate: "2020-01-01", tenorMonths: 12, rollover: false, fromWalletId: "wallet-bca" },
  } })
  expect(response.ok()).toBeTruthy()
  const { wallet } = await response.json()
  await page.goto("/wallets")
  await page.getByRole("button", { name: "More options for Review deposito" }).click()
  await page.getByRole("menuitem", { name: "Edit details" }).click()
  const dialog = page.getByRole("dialog")
  await dialog.getByLabel("Amount put in", { exact: true }).fill("1200000")
  await expect(dialog).toContainText("Rp 200.000 more comes from BCA")
  await expect(dialog.getByRole("group", { name: "Renew automatically?" })).toBeVisible()
  await page.waitForTimeout(250)
  await page.screenshot({ path: info.outputPath("principal-desktop.png") })
  await dialog.getByRole("button", { name: "Save changes" }).click()
  await expect(dialog).toHaveCount(0)
  const corrected = await read(request)
  expect(corrected.wallets.find((w: { id: string }) => w.id === wallet.id).deposito.principal).toBe(1_200_000)
  expect(corrected.wallets.find((w: { id: string }) => w.id === "wallet-bca").balance).toBe(7_542_300)
  await expect(page.getByRole("main")).toContainText("7.542.300")
  await page.getByRole("button", { name: "Move money from Review deposito", exact: true }).click()
  await expect(page.getByRole("dialog")).toContainText("Undo for ten seconds")
  await page.getByRole("dialog").getByRole("button", { name: "Move money", exact: true }).click()
  await expect(page.getByText("Money moved", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Undo", exact: true }).click()
  await expect(page.getByText("Money moved back", { exact: true })).toBeVisible()
  await expect(page.getByRole("main")).toContainText("7.542.300")
  const undone = await read(request)
  expect(undone.wallets).toEqual(corrected.wallets)
  expect(undone.transactions).toEqual(corrected.transactions)
  await page.reload()
  await expect(page.getByRole("button", { name: "Move money from Review deposito", exact: true })).toBeVisible()
  // Return the fixture's principal and remove its correction history with Delete Undo left unused.
  expect((await request.delete(`/api/wallets/${wallet.id}`)).ok()).toBeTruthy()
})

test("CSV suggestions require a choice, replace the other side once, and Undo restores it", async ({ page, request }, info) => {
  const original = await request.post("/api/transactions", { data: { type: "income", walletId: "wallet-jago", categoryId: "cat-salary", amount: 75000, date: `${today}T12:00:00+07:00`, description: "Received from BCA" } })
  const { transaction } = await original.json()
  const before = await read(request)
  await page.goto("/transactions")
  await page.getByRole("button", { name: "Import CSV", exact: true }).first().click()
  await page.locator('input[type="file"]').setInputFiles({ name: "review.csv", mimeType: "text/csv", buffer: Buffer.from(`Date,Description,Amount\n${today},Transfer to Jago,-75000`) })
  const dialog = page.getByRole("dialog")
  const select = dialog.getByRole("combobox", { name: "Record Transfer to Jago as" })
  await expect(select).toHaveValue("")
  expect((await read(request)).transactions).toEqual(before.transactions)
  await select.selectOption(transaction.id)
  await expect(dialog).toContainText("its balance stays the same")
  await expect(dialog.getByRole("combobox", { name: "Category for Transfer to Jago" })).toHaveCount(0)
  await page.waitForTimeout(250)
  await page.screenshot({ path: info.outputPath("csv-desktop.png") })
  await dialog.getByRole("button", { name: "Import 1 transaction", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const after = await read(request)
  expect(after.wallets.find((w: { id: string }) => w.id === "wallet-jago").balance).toBe(before.wallets.find((w: { id: string }) => w.id === "wallet-jago").balance)
  expect(after.wallets.find((w: { id: string }) => w.id === "wallet-bca").balance).toBe(before.wallets.find((w: { id: string }) => w.id === "wallet-bca").balance - 75000)
  expect(after.transactions.find((tx: { id: string }) => tx.id === transaction.id)).toBeUndefined()
  await expect(page.getByRole("main")).toContainText("Transfer to Jago")
  await page.getByRole("button", { name: "Undo", exact: true }).click()
  await expect.poll(async () => (await read(request)).transactions).toEqual(before.transactions)
  await expect(page.getByRole("main")).toContainText("Received from BCA")
  await page.reload()
  await expect(page.getByRole("main")).toContainText("Received from BCA")
  await request.delete(`/api/transactions/${transaction.id}`)
})

test("CSV review stays usable on a narrow phone in dark mode", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => localStorage.setItem("theme", "dark"))
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/transactions")
  await page.getByRole("button", { name: "Import CSV", exact: true }).first().click()
  await page.locator('input[type="file"]').setInputFiles({ name: "phone.csv", mimeType: "text/csv", buffer: Buffer.from(`Date,Description,Amount\n${today},Transfer to Bank Jago,-250000\n${today},Lunch,-25000`) })
  const dialog = page.getByRole("dialog")
  const select = dialog.getByRole("combobox", { name: "Record Transfer to Bank Jago as" })
  await select.selectOption("wallet-jago")
  await expect(dialog).toContainText("adds Rp 250.000 into Bank Jago")
  await select.focus()
  await expect(select).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.waitForTimeout(250)
  await page.screenshot({ path: info.outputPath("csv-phone-dark.png") })
  await select.selectOption("")
  await expect(dialog.getByRole("combobox", { name: "Category for Transfer to Bank Jago" })).toBeVisible()
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  expect(errors).toEqual([])
})
