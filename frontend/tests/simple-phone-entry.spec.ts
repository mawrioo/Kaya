for (const [sentence, type, amount, bcaChange, jagoChange] of [
  ["paid 35rb Food BCA yesterday", "expense", 35000, -35000, 0],
  ["received Salary 5jt in Bank Jago today", "income", 5000000, 0, 5000000],
  ["transfer 500rb from BCA to Bank Jago", "transfer", 500000, -500000, 500000],
] as const) {
  test(`compact ${type} review saves exactly once with correct balances`, async ({ page, request }, info) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto("/transactions")
    const before = await (await request.get("/api/data")).json()
    await prepare(page, sentence)
    await expect(page.getByRole("heading", { name: `Review ${type}` })).toBeVisible()
    await expect(page.getByRole("region", { name: "Transaction review" })).toBeVisible()
    await expect(page.getByLabel("Amount", { exact: true })).toBeHidden()
    await expect(page.getByRole("button", { name: "Undo last change" })).toHaveCount(0)
    await page.getByRole("button", { name: "Edit details", exact: true }).click()
    await page.getByLabel("Note (optional)").fill(`Simple ${type} test`)
    await page.getByLabel("Amount", { exact: true }).press("Enter")
    expect((await (await request.get("/api/data")).json()).transactions).toHaveLength(before.transactions.length)
    await expect(page.getByRole("button", { name: "Save", exact: true })).toHaveCount(0)
    await page.getByRole("button", { name: "Review", exact: true }).click()
    await page.screenshot({ path: info.outputPath(`${type}-review.png`), animations: "disabled" })
    await page.getByRole("button", { name: "Save", exact: true }).dblclick()
    await expect(page.getByRole("heading", { name: "Transaction added", exact: true })).toBeVisible()
    const after = await (await request.get("/api/data")).json()
    expect(after.transactions).toHaveLength(before.transactions.length + 1)
    expect(after.transactions.find((entry: { description: string }) => entry.description === `Simple ${type} test`)).toMatchObject({ type, amount })
    const balance = (data: typeof after, id: string) => data.wallets.find((wallet: { id: string }) => wallet.id === id).balance
    expect(balance(after, "wallet-bca") - balance(before, "wallet-bca")).toBe(bcaChange)
    expect(balance(after, "wallet-jago") - balance(before, "wallet-jago")).toBe(jagoChange)
    await page.getByRole("button", { name: "Add another", exact: true }).click()
    await expect(page.getByLabel("What happened?", { exact: true })).toBeFocused()
    await expect(page.getByLabel("What happened?", { exact: true })).toHaveValue("")
  })
}

test("one question, natural correction and manual entry stay separate from saving", async ({ page, request }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/goals")
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.screenshot({ path: info.outputPath("entry.png"), animations: "disabled" })
  await page.getByLabel("What happened?", { exact: true }).fill("bought lunch from BCA yesterday")
  await page.getByRole("button", { name: "Review", exact: true }).click()
  await expect(page.locator("#tx-question")).toHaveText("How much was it?")
  await expect(page.getByLabel("Amount", { exact: true })).toBeHidden()
  await page.getByLabel("Reply or correction").fill("35rb")
  await page.getByLabel("Reply or correction").press("Enter")
  await expect(page.getByRole("heading", { name: "Review expense" })).toBeVisible()
  await expect(page.getByLabel("Reply or correction")).toHaveCount(0)
  await page.getByRole("button", { name: "Edit details", exact: true }).click()
  await page.getByLabel("Reply or correction").fill("make that 40rb")
  await page.getByLabel("Reply or correction").press("Enter")
  await expect(page.getByLabel("Amount", { exact: true })).toHaveValue("40.000")
  await page.getByRole("button", { name: "Review", exact: true }).click()
  await expect(page.getByRole("region", { name: "Transaction review" })).toContainText("Rp 40.000")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  expect((await (await request.get("/api/data")).json()).transactions).toHaveLength(41)
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.getByRole("button", { name: "Enter manually", exact: true }).click()
  await expect(page.getByLabel("Amount", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Close", exact: true }).click()
})

test("favourites and remembered categories remain available through More and Settings", async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/")
  await prepare(page, "paid 35rb Food BCA")
  await moreEntry(page, "Save as favourite")
  await page.getByLabel("Favourite name", { exact: true }).fill("Lunch")
  await page.getByRole("button", { name: "Save favourite", exact: true }).click()
  await expect(page.getByRole("status").filter({ hasText: "Favourite saved" })).toBeVisible()
  await page.getByRole("button", { name: "Back", exact: true }).click()
  await page.getByRole("button", { name: "Edit details", exact: true }).click()
  await page.getByRole("checkbox", { name: /Remember this category/ }).check()
  await page.getByRole("button", { name: "Review", exact: true }).click()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await page.getByRole("button", { name: "Done", exact: true }).click()
  await page.getByRole("button", { name: "More pages" }).click()
  await page.getByRole("button", { name: "Settings", exact: true }).click()
  await page.getByRole("button", { name: "Entry preferences", exact: true }).click()
  await expect(page.getByRole("dialog", { name: "Entry preferences" })).toBeVisible()
  await page.getByRole("button", { name: "Edit favourite Lunch", exact: true }).click()
  await page.getByLabel("Favourite name", { exact: true }).fill("Lunch at desk")
  await page.getByLabel("Amount", { exact: true }).fill("45000")
  await page.getByRole("checkbox", { name: /Keep this amount/ }).check()
  await page.getByLabel("Amount", { exact: true }).fill("")
  await expect(page.getByRole("button", { name: "Update favourite", exact: true })).toBeDisabled()
  await page.getByRole("checkbox", { name: /Keep this amount/ }).uncheck()
  await expect(page.getByRole("button", { name: "Update favourite", exact: true })).toBeEnabled()
  await page.getByLabel("Amount", { exact: true }).fill("45000")
  await page.getByRole("checkbox", { name: /Keep this amount/ }).check()
  await page.getByRole("button", { name: "Update favourite", exact: true }).click()
  await expect.poll(async () => (await (await request.get("/api/assistant")).json()).templates[0]?.draft.amount).toBe(45000)
  await page.getByRole("button", { name: "Forget category for food", exact: true }).click()
  await expect.poll(async () => (await (await request.get("/api/assistant")).json()).rules.length).toBe(0)
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await moreEntry(page, "Use a favourite")
  await page.getByRole("button", { name: "Lunch at desk", exact: true }).click()
  await expect(page.getByRole("region", { name: "Transaction review" })).toContainText("Rp 45.000")
  expect((await (await request.get("/api/data")).json()).transactions).toHaveLength(42)
})

for (const theme of ["light", "dark"] as const) {
  test(`entry and compact review stay clear from 320px through desktop (${theme})`, async ({ page }, info) => {
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    await page.addInitScript(value => localStorage.setItem("theme", value), theme)
    for (const width of [320, 390, 430, 1440]) {
      await page.setViewportSize({ width, height: 844 })
      await page.goto("/goals")
      await page.getByRole("button", { name: "Quick add", exact: true }).click()
      await expect(page.getByRole("button", { name: "Review", exact: true })).toBeVisible()
      await expect(page.getByRole("button", { name: "Simple expense", exact: true })).toHaveCount(0)
      if (width === 390 || width === 1440) await page.screenshot({ path: info.outputPath(`${theme}-${width}-entry.png`), animations: "disabled" })
      await page.getByLabel("What happened?", { exact: true }).fill("paid 10rb coffee BCA")
      await page.getByRole("button", { name: "Review", exact: true }).click()
      await expect(page.getByRole("heading", { name: "Review expense" })).toBeVisible()
      await expect(page.getByRole("button", { name: "Save", exact: true })).toBeInViewport()
      expect(await page.getByRole("dialog").evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (width === 390 || width === 1440) await page.screenshot({ path: info.outputPath(`${theme}-${width}-review.png`), animations: "disabled" })
      await page.keyboard.press("Escape")
    }
    expect(errors).toEqual([])
  })
}
