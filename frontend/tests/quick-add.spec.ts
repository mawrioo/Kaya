import { expect, test } from "./browser-fixtures"
import type { AppData } from "../lib/types"

test.beforeAll(async ({ request }) => {
  const data: AppData = await (await request.get("/api/data")).json()
  expect(data.transactions).toHaveLength(41)
  expect(data.wallets.find((wallet) => wallet.name === "BCA")?.balance).toBe(8_742_300)
})

test("quick add fills, reviews, handles a failed save, and persists only after saving", async ({ page, request }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  const initial: AppData = await (await request.get("/api/data")).json()
  await page.goto("/")
  const trigger = page.getByRole("button", { name: "Quick add", exact: true })
  await trigger.click()
  await page.getByRole("button", { name: "Simple expense", exact: true }).click()
  const line = page.getByRole("textbox", { name: "Your expense" })
  await expect(line).toBeFocused()
  await expect(page.getByLabel("Amount", { exact: true })).toHaveCount(0)
  await line.fill("Sate and es teh dinner 25rb BCA")
  await line.press("Enter")
  await expect(page.getByLabel("Amount", { exact: true })).toHaveValue("25.000")
  await expect(page.getByLabel("Amount", { exact: true })).toBeFocused()
  await expect(page.getByLabel("Note (optional)")).toHaveValue("Sate and es teh dinner")
  await expect(page.locator("#tx-wallet")).toContainText("BCA")
  await expect(page.locator("#tx-category")).toContainText("Food")
  expect((await (await request.get("/api/data")).json()).transactions).toHaveLength(initial.transactions.length)

  await page.locator("#tx-category").click()
  await page.getByRole("option", { name: "Shopping", exact: true }).click()
  await line.fill("kopi 25rb BCA")
  await page.getByRole("button", { name: "Fill form", exact: true }).click()
  await expect(page.locator("#tx-category")).toContainText("Shopping")
  await line.fill("kopi 25rb 30rb BCA")
  await line.press("Enter")
  await expect(page.getByRole("alert")).toContainText("more than one amount")
  await expect(page.getByLabel("Amount", { exact: true })).toHaveValue("25.000")
  await expect(page.getByLabel("Note (optional)")).toHaveValue("kopi")
  await line.fill("kopi 25rb BCA")
  await line.press("Enter")
  await page.getByLabel("Note (optional)").fill("Quick add browser check")

  await page.route("**/api/transactions", async (route) => {
    if (route.request().method() === "POST") await route.fulfill({ status: 500, json: { error: "Test save failure" } })
    else await route.continue()
  })
  await page.getByRole("button", { name: "Add transaction", exact: true }).click()
  await expect(page.getByText("Test save failure", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Note (optional)")).toHaveValue("Quick add browser check")
  await page.unroute("**/api/transactions")
  await page.getByRole("button", { name: "Add transaction", exact: true }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(trigger).toBeFocused()
  const saved: AppData = await (await request.get("/api/data")).json()
  expect(saved.transactions).toHaveLength(initial.transactions.length + 1)
  expect(saved.wallets.find((wallet) => wallet.name === "BCA")?.balance).toBe(8_717_300)
  expect(saved.transactions.find((tx) => tx.description === "Quick add browser check")).toMatchObject({ type: "expense", amount: 25000 })
  await page.reload()
  await expect(page.getByText("Quick add browser check", { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test("cancel saves nothing, a fresh entry resets, and the regular form stays familiar", async ({ page, request }) => {
  const initial: AppData = await (await request.get("/api/data")).json()
  await page.goto("/transactions")
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.getByRole("button", { name: "Simple expense", exact: true }).click()
  await page.getByLabel("Your expense").fill("new merchant 12,5rb")
  await page.getByRole("button", { name: "Fill form", exact: true }).click()
  await expect(page.getByLabel("Amount", { exact: true })).toHaveValue("12.500")
  await expect(page.getByRole("status").filter({ hasText: "Form filled" })).toContainText("Kept wallet")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  expect((await (await request.get("/api/data")).json()).transactions).toHaveLength(initial.transactions.length)
  await page.getByRole("button", { name: "Quick add", exact: true }).click()
  await page.getByRole("button", { name: "Simple expense", exact: true }).click()
  await expect(page.getByLabel("Your expense")).toHaveValue("")
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Add transaction", exact: true }).click()
  await expect(page.getByLabel("Amount", { exact: true })).toBeFocused()
  await expect(page.getByLabel("Your expense")).toHaveCount(0)
})

